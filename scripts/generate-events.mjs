#!/usr/bin/env node
// Generates src/events.generated.ts from the event catalog.
//
//   node scripts/generate-events.mjs                                       from the snapshot next to this script
//   node scripts/generate-events.mjs https://api.dzbot.de/api/developer/events   from the live catalog (refreshes the snapshot)
//   node scripts/generate-events.mjs catalog.json                          from a file
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const snapshot = resolve(here, 'events-catalog.json')
const source = process.argv[2] ?? snapshot

let catalog
if (/^https?:\/\//.test(source)) {
  const response = await fetch(source)
  if (!response.ok) throw new Error(`${source}: HTTP ${response.status}`)
  catalog = await response.json()
  for (const event of catalog.events) delete event.sample
  writeFileSync(snapshot, JSON.stringify(catalog, null, 1) + '\n')
} else {
  catalog = JSON.parse(readFileSync(source, 'utf8'))
}

// A 'null' type comes from a sample that happened to be null, so it maps to unknown like anything else not listed.
const SCALARS = { int: 'number', float: 'number', string: 'string', bool: 'boolean' }

function node() {
  return { type: null, children: new Map(), element: null }
}

// `items[].name: string` → items is an array whose elements have name
function tree(schema) {
  const root = node()
  for (const [path, type] of Object.entries(schema)) {
    let current = root
    const segments = path.split('.')
    segments.forEach((segment, index) => {
      const isArray = segment.endsWith('[]')
      const key = isArray ? segment.slice(0, -2) : segment
      if (!current.children.has(key)) current.children.set(key, node())
      let target = current.children.get(key)
      if (isArray) {
        target.type ??= 'array'
        target.element ??= node()
        target = target.element
      }
      if (index === segments.length - 1) target.type = type
      current = target
    })
  }
  return root
}

const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/

function render(n, indent) {
  const raw = n.type ?? 'object'
  const nullable = raw.startsWith('?')
  const type = nullable ? raw.slice(1) : raw
  let ts
  if (type === 'array') {
    ts = n.element && (n.element.type || n.element.children.size) ? `Array<${render(n.element, indent)}>` : 'unknown[]'
  } else if (type === 'object' || (n.children.size > 0 && !SCALARS[type])) {
    if (n.children.size === 0) {
      ts = 'Record<string, unknown>'
    } else {
      const pad = '  '.repeat(indent + 1)
      const lines = [...n.children].map(([key, child]) => `${pad}${identifier.test(key) ? key : JSON.stringify(key)}: ${render(child, indent + 1)}`)
      ts = `{\n${lines.join('\n')}\n${'  '.repeat(indent)}}`
    }
  } else {
    ts = SCALARS[type] ?? 'unknown'
  }
  return nullable && ts !== 'unknown' ? `${ts} | null` : ts
}

const events = [...catalog.events].sort((a, b) => a.name.localeCompare(b.name))
const out = [
  '// Generated by scripts/generate-events.mjs from the dzbot event catalog (GET /api/developer/events). Do not edit.',
  '',
  'export interface DzbotEventPayloads {',
]
for (const event of events) {
  const doc = [event.description, `Scope: ${event.scope}. Readable with: ${(event.readRights ?? []).join(', ') || '-'}.`].filter(Boolean)
  out.push(`  /** ${doc.join(' ').replace(/\*\//g, '* /')} */`)
  out.push(`  ${JSON.stringify(event.name)}: ${render(tree(event.schema ?? {}), 1)}`)
}
out.push('}', '')
out.push(`export const EVENT_NAMES = [\n${events.map((e) => `  ${JSON.stringify(e.name)},`).join('\n')}\n] as const`, '')

writeFileSync(resolve(here, '../src/events.generated.ts'), out.join('\n'))
console.log(`Wrote ${events.length} event types to src/events.generated.ts`)
